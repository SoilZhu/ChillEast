def generate_dialect_arb(locale_tag, specific_dict, tone_replacements, out_path):
    out = {"@@locale": locale_tag}
    for k, v in base_keys.items():
        if k in specific_dict:
            res = specific_dict[k]
        else:
            res = v
            # Apply common tone replacements
            for old, new in tone_replacements.items():
                # Avoid touching placeholders!
                parts = re.split(r"(\{[a-zA-Z0-9_]+\})", res)
                new_parts = []
                for p in parts:
                    if p.startswith("{") and p.endswith("}"):
                        new_parts.append(p)
                    else:
                        new_parts.append(p.replace(old, new))
                res = "".join(new_parts)
        out[k] = res
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print(f"Generated {out_path}")

