# Generate yue by starting from cc_hk converted text + yue dict
out_yue = {"@@locale": "yue"}
for k, v in base_keys.items():
    if k in yue_dict:
        out_yue[k] = yue_dict[k]
    else:
        parts = re.split(r"(\{[a-zA-Z0-9_]+\})", v)
        converted_parts = []
        for p in parts:
            if p.startswith("{") and p.endswith("}"):
                converted_parts.append(p)
            else:
                conv = cc_hk.convert(p)
                conv = conv.replace("設置", "設置").replace("登錄", "登入").replace("默認", "預設")
                conv = conv.replace("正在", "緊").replace("請問", "唔該問下").replace("請", "唔該")
                converted_parts.append(conv)
        out_yue[k] = "".join(converted_parts)

with open("lib/l10n/app_yue.arb", "w", encoding="utf-8") as f:
    json.dump(out_yue, f, ensure_ascii=False, indent=2)
